import importlib.util
import json
import os
import subprocess
import tempfile
import unittest

SCRIPT = os.path.join(os.path.dirname(__file__), "..", "skills", "playbook", "history.py")
spec = importlib.util.spec_from_file_location("playbook_history", SCRIPT)
history = importlib.util.module_from_spec(spec)
spec.loader.exec_module(history)

TS = "2026-10-09T18:07:36.000Z"


def user(content, **extra):
    return {"type": "user", "timestamp": TS, "message": {"role": "user", "content": content}, **extra}


def assistant(*blocks):
    return {"type": "assistant", "timestamp": TS, "message": {"role": "assistant", "content": list(blocks)}}


def call(name, tool_id="t1", **inp):
    return {"type": "tool_use", "id": tool_id, "name": name, "input": inp}


def result(text, tool_id="t1", error=False):
    return user([{"type": "tool_result", "tool_use_id": tool_id, "content": text, "is_error": error}])


def write_transcript(path, entries):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        for entry in entries:
            f.write(json.dumps(entry) + "\n")
    return path


def git(*args, cwd):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


class DigestTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def digest_of(self, *entries):
        path = write_transcript(os.path.join(self.tmp.name, "s.jsonl"), entries)
        return "\n".join(history.digest(path))

    def test_prints_user_prompts_and_bash_commands(self):
        out = self.digest_of(
            user("Klient prosi o eksport sprzedazy za wrzesien"),
            assistant(call("Bash", command="mysql shop < scripts/queries/monthly_export.sql")),
            result("ok"),
        )
        self.assertIn("USER: Klient prosi o eksport sprzedazy za wrzesien", out)
        self.assertIn("$ mysql shop < scripts/queries/monthly_export.sql", out)

    def test_never_prints_tool_results(self):
        out = self.digest_of(
            assistant(call("Bash", command="mysql shop -e 'select email from customers'")),
            result("jan.kowalski@example.com"),
            assistant(call("Bash", "t2", command="php artisan import:run")),
            result("Connection refused for jan.kowalski@example.com", "t2", error=True),
        )
        self.assertNotIn("kowalski", out)

    def test_marks_failed_commands(self):
        out = self.digest_of(
            assistant(call("Bash", command="php artisan import:run")),
            result("boom", error=True),
        )
        self.assertIn("$ php artisan import:run [failed]", out)

    def test_never_prints_assistant_text(self):
        out = self.digest_of(assistant({"type": "text", "text": "Customer Jan Kowalski has 3 orders"}))
        self.assertNotIn("Kowalski", out)

    def test_drops_system_reminders_and_meta_messages(self):
        out = self.digest_of(
            user("fix the import<system-reminder>internal note</system-reminder>"),
            user("Caveat: generated by hooks", isMeta=True),
        )
        self.assertIn("USER: fix the import", out)
        self.assertNotIn("internal note", out)
        self.assertNotIn("Caveat", out)

    def test_drops_command_output_pasted_into_user_messages(self):
        out = self.digest_of(
            user("<bash-input>mysql shop -e 'select email from customers'</bash-input>"
                 "<bash-stdout>jan.kowalski@example.com</bash-stdout><bash-stderr>warn kowalski</bash-stderr>"),
            user("<local-command-stdout>kowalski total 12</local-command-stdout>"),
        )
        self.assertIn("select email from customers", out)
        self.assertNotIn("kowalski", out)

    def test_drops_notices_and_pasted_text_that_are_not_the_users_words(self):
        out = self.digest_of(
            user("<task-notification><result>kowalski 12 orders</result></task-notification>"),
            user("export this <pasted_content id=\"a1\">From: jan.kowalski@example.com</pasted_content id=\"a1\"> please"),
            user("<side-sessions-event>kowalski</side-sessions-event>"
                 "<artifact-view-context>kowalski</artifact-view-context>"
                 "<recent-project-folders>kowalski</recent-project-folders>"),
        )
        self.assertNotIn("kowalski", out)
        self.assertIn("USER: export this [pasted text] please", out)
        self.assertEqual(out.count("USER:"), 1)

    def test_lists_edited_files(self):
        out = self.digest_of(assistant(call("Edit", file_path="/repo/app/Jobs/Import.php")))
        self.assertIn("edit /repo/app/Jobs/Import.php", out)

    def test_keeps_whole_multiline_command(self):
        out = self.digest_of(assistant(call("Bash", command="mysql shop <<'SQL'\nselect 1\nfrom orders\nSQL")))
        self.assertIn("from orders", out)

    def test_redacts_secrets_in_commands(self):
        out = self.digest_of(
            assistant(call("Bash", command="mysql -u app -pS3cretPw shop")),
            assistant(call("Bash", command="API_TOKEN=tok123 curl -H 'Authorization: Bearer abc.def' https://u:pw9@db.example.com")),
            assistant(call("Bash", command="php artisan tinker --execute='$password = \"hunter2\"'")),
        )
        for secret in ("S3cretPw", "tok123", "abc.def", "pw9", "hunter2"):
            self.assertNotIn(secret, out)
        self.assertIn("mysql -u app -p[redacted] shop", out)


class SessionsTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = os.path.realpath(tmp.name)
        self.projects = os.path.join(self.root, "projects")
        self.main = os.path.join(self.root, "app")
        os.makedirs(self.main)
        git("init", "-q", "-b", "main", cwd=self.main)
        git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "init", cwd=self.main)

    def transcript(self, cwd, session="s1"):
        folder = os.path.join(self.projects, history.project_key(cwd))
        return write_transcript(os.path.join(folder, session + ".jsonl"), [user("hello", cwd=cwd)])

    def test_project_key_replaces_every_non_alphanumeric_character(self):
        self.assertEqual(history.project_key("/Users/me/Dev/my_app.v2"), "-Users-me-Dev-my-app-v2")

    def test_main_checkout_from_a_linked_worktree(self):
        wt = os.path.join(self.root, "app-feature")
        git("worktree", "add", "-q", wt, "-b", "feature", cwd=self.main)
        self.assertEqual(history.main_checkout(wt), self.main)
        self.assertEqual(history.main_checkout(self.main), self.main)

    def test_includes_main_checkout_sessions(self):
        path = self.transcript(self.main)
        self.assertEqual(history.sessions(self.projects, self.main), [path])

    def test_includes_nested_worktree_even_after_it_is_removed(self):
        path = self.transcript(os.path.join(self.main, ".claude", "worktrees", "gone"))
        self.assertEqual(history.sessions(self.projects, self.main), [path])

    def test_includes_sibling_worktree(self):
        wt = os.path.join(self.root, "app-feature")
        git("worktree", "add", "-q", wt, "-b", "feature", cwd=self.main)
        path = self.transcript(wt)
        self.assertEqual(history.sessions(self.projects, self.main), [path])

    def test_excludes_other_project_with_the_same_prefix(self):
        other = os.path.join(self.root, "app-admin")
        os.makedirs(other)
        git("init", "-q", cwd=other)
        self.transcript(other)
        self.assertEqual(history.sessions(self.projects, self.main), [])

    def test_ignores_subagent_transcripts(self):
        path = self.transcript(self.main)
        write_transcript(os.path.join(self.projects, history.project_key(self.main), "s1", "subagents", "a.jsonl"),
                         [user("sub", cwd=self.main)])
        self.assertEqual(history.sessions(self.projects, self.main), [path])


if __name__ == "__main__":
    unittest.main()
